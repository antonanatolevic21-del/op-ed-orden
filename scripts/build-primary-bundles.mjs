async function bundle(files, output, comment) {
  const contents = await Promise.all(files.map(file => readFile(file, 'utf8')));
  const sections = files.map((file, index) => `/* ${file} */\n${contents[index].trim()}`);
  await writeFile(output, `${comment}\n${sections.join('\n\n')}\n`, 'utf8');
}

